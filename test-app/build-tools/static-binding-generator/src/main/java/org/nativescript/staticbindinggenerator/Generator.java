    public Generator(File outputDir, List<DataRow> libs, boolean suppressCallJSMethodExceptions) throws IOException {
        this.outputDir = outputDir;
        this.libs = libs;
        this.fileSystemHelper = new FileSystemHelperImpl(InputParameters.getCurrent().getThrowOnError());
        ClassesCollection classesCollection = readClasses(libs);
        this.classes = classesCollection.getRegularClasses();
        this.nonPublicNestedClasses = classesCollection.getNonPublicNestedClasses();
        androidClassChecker = new AndroidClassCheckerImpl(classes);
        this.suppressCallJSMethodExceptions = suppressCallJSMethodExceptions;
        this.contentKeyedBindings = InputParameters.getCurrent().getContentKeyedBindings();
    }

    public void writeBindings(String filename) throws IOException, ClassNotFoundException {
        fileSystemHelper.cleanPreviouslyAutoGeneratedSbgFiles(this.outputDir);
        Binding[] bindings = generateBindings(filename);
        Map<File, Binding> writtenFiles = new HashMap<File, Binding>();
        for (Binding b : bindings) {
            Binding written = writtenFiles.putIfAbsent(b.getFile(), b);
            if (written == null) {
                writeGeneratedFile(b.getFile(), b.getContent());
            } else if (!written.getContent().equals(b.getContent())) {
                throw new IOException("Two extends generate the class " + b.getFile() + " with different contents, from " + written.getSource() + " and from " + b.getSource() + ".\nPlease change the name of one of the extended classes.");
            }
        }

        if (contentKeyedBindings) {
            File markerDir = new File(outputDir, DEFAULT_PACKAGE_NAME.replace('.', '/'));
            markerDir.mkdirs();
            writeGeneratedFile(new File(markerDir, CONTENT_KEYED_BINDINGS_CLASS + JAVA_EXT), getContentKeyedBindingsSource());
        }
    }

    private static void writeGeneratedFile(File file, String content) throws IOException {
        try (PrintStream ps = new PrintStream(file)) {
            ps.append(AUTO_GENERATED_FILE_PROLOGUE);
            ps.append(content);
        }
    }

    /**
     * The runtime names classes after their content only when this class is in
     * the app, so the generator and the runtime cannot disagree on the mode.
     */
    public String getContentKeyedBindingsSource() {
        StringBuilder sb = new StringBuilder();
        sb.append("package ").append(DEFAULT_PACKAGE_NAME).append(";").append(LINE_SEPARATOR).append(LINE_SEPARATOR);
        sb.append("public final class ").append(CONTENT_KEYED_BINDINGS_CLASS).append(" {").append(LINE_SEPARATOR);
        sb.append("    public static final String[] COLLISIONS = {").append(LINE_SEPARATOR);
        for (String name : contentNameCollisions) {
            sb.append("        \"").append(name).append("\",").append(LINE_SEPARATOR);
        }
        sb.append("    };").append(LINE_SEPARATOR).append(LINE_SEPARATOR);
        sb.append("    private ").append(CONTENT_KEYED_BINDINGS_CLASS).append("() {").append(LINE_SEPARATOR);
        sb.append("    }").append(LINE_SEPARATOR);
        sb.append("}").append(LINE_SEPARATOR);
        return sb.toString();
    }

